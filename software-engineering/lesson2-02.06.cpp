#include <cmath>
#include <iostream>
#include <print>

int main() {
	double a[1000];
	int n = 0;
	std::cin >> n;
	for (int i = 0; i < n; ++i)
		std::cin >> a[i];

	for (int i = 0; i < n - 1; ++i)   //пузырёк, нужен для медианы
		for (int j = 0; j < n - 1 - i; ++j)
			if (a[j] > a[j + 1]) { double t = a[j]; a[j] = a[j + 1]; a[j + 1] = t; }

	double min = a[0];
	double max = a[n - 1];
	double median = (n % 2) ? a[n / 2] : (a[n / 2 - 1] + a[n / 2]) / 2.0;

	double sum = 0.0;
	for (int i = 0; i < n; ++i)
		sum += a[i];
	double mean = sum / n;

	double s2 = 0.0;
	for (int i = 0; i < n; ++i)
		s2 += (a[i] - mean) * (a[i] - mean);
	double stddev = std::sqrt(s2 / n);

	std::print("min = {}\nmax = {}\nmedian = {}\nmean = {}\nstddev = {}\n", min, max, median, mean, stddev);
	return 0;
}
